function pointInPoly(lon: number, lat: number, poly: Poly): boolean {
  let inside = false
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i]!
    const [xj, yj] = poly[j]!
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) {
      inside = !inside
    }
  }
  return inside
}

export function isLand(lat: number, lon: number): boolean {
  for (const poly of CONTINENTS) if (pointInPoly(lon, lat, poly)) return true
  return false
}

export function subsolarLongitude(now = new Date()): number {
  const hours = now.getUTCHours() + now.getUTCMinutes() / 60
  return -15 * (hours - 12)
}

export function isDaylight(lon: number, subsolar: number): boolean {
  const d = Math.abs((((lon - subsolar + 180) % 360) + 360) % 360 - 180)
  return d < 90
}
